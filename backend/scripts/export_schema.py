"""Write the Postgres schema (from the SQLAlchemy models) to supabase/migrations."""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from sqlalchemy.dialects import postgresql  # noqa: E402
from sqlalchemy.schema import CreateIndex, CreateTable  # noqa: E402

from app.models import Base  # noqa: E402

out = ["-- FinDost AI schema (generated by backend/scripts/export_schema.py)", ""]
for table in Base.metadata.sorted_tables:
    ddl = str(CreateTable(table, if_not_exists=True).compile(dialect=postgresql.dialect())).strip()
    out.append(ddl + ";")
    for index in table.indexes:
        out.append(str(CreateIndex(index, if_not_exists=True).compile(dialect=postgresql.dialect())).strip() + ";")
    out.append(f'ALTER TABLE public."{table.name}" ENABLE ROW LEVEL SECURITY;')
    out.append("")
path = os.path.join(os.path.dirname(__file__), "..", "..", "supabase", "migrations", "20261010000000_findost_schema.sql")
os.makedirs(os.path.dirname(path), exist_ok=True)
with open(path, "w") as f:
    f.write("\n".join(out))
print("wrote", os.path.normpath(path))
